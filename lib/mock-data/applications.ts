export function computeApplicationSummary(app: Application): ApplicationSummary {
  const verified = app.documents.filter((d) => d.status === "verified_demo").length;
  const uploaded = app.documents.length;
  const required = Math.max(12, uploaded);
  const openCorrections = app.corrections.filter((c) => c.status === "open").length;
  const walletStatus = app.wallets[0]?.verificationStatus ?? "not_started";

  let completedChecks = 0;
  if (app.business.legalName && app.business.pan) completedChecks += 15;
  if (app.signatory.fullName && app.signatory.pan) completedChecks += 15;
  if (app.beneficialOwners.length > 0) completedChecks += 15;
  if (app.financial.bankAccount.accountNumber) completedChecks += 15;
  if (app.wallets.length > 0) completedChecks += 15;
  if (app.declarations.every((d) => d.acknowledged)) completedChecks += 15;
  if (app.status !== "draft") completedChecks += 10;

  return {
    id: app.id,
    reference: app.reference,
    businessName: app.business.legalName || "Untitled Corporate Entity",
    entityType: app.business.entityType,
    status: app.status,
    createdAt: app.createdAt,
    updatedAt: app.updatedAt,
    submittedAt: app.submittedAt,
    assignedReviewerId: app.assignedReviewerId ?? "usr-rev-1",
    assignedReviewerName: app.assignedReviewerId === "usr-pan-rev-1" ? "Sneha Iyer" : "Neha Kulkarni",
    documentProgress: { verified, uploaded, required },
    videoKycStatus: app.videoKyc.status,
    walletStatus,
    openCorrections,
    progressPercent: Math.min(100, completedChecks),
  };
}

export const mockApplicationSummaries: ApplicationSummary[] = mockApplications.map(computeApplicationSummary);
